// Execute is the entry point invoked from cmd/maz/main.go.
//
// It replaces the simpler root.Execute() call so that the command that failed
// is available for richer error messages: arg-count errors get usage + example,
// and misspelled flags get a "did you mean --X?" suggestion.
func Execute() {
	root := newRootCmd()
	cmd, err := root.ExecuteC()
	if err != nil {
		var se silentError
		if errors.As(err, &se) {
			// silentError's user-facing message was already rendered by
			// the subcommand (or by the FlagErrorFunc); suppress the
			// duplicate and exit with the embedded code.
			os.Exit(se.code)
		}
		if isArgCountError(err.Error()) {
			var errW io.Writer = os.Stderr
			if cmd != nil {
				errW = cmd.ErrOrStderr()
			}
			printArgCountError(errW, cmd, err)
			os.Exit(output.ExitUsage)
		}
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// ── WS9: Arg / flag error helpers ────────────────────────────────────────────

// setFlagErrorFunc registers a FlagErrorFunc on root. Because cobra inherits
// the FlagErrorFunc from the parent chain, setting it once on root is enough
// for all subcommands.
func setFlagErrorFunc(root *cobra.Command) {
	root.SetFlagErrorFunc(func(c *cobra.Command, err error) error {
		errMsg := err.Error()
		errW := c.ErrOrStderr()
		styled := interactive.ShouldStyle(c, errW)
		col := colorizer.New(styled, errW)

		// Always print the raw error.
		//nolint:errcheck // best-effort stderr write
		fmt.Fprintf(errW, "%s\n", col.Err("✗ "+errMsg))

		// Suggest the closest flag when the user mistyped one.
		if flagName := extractUnknownFlagName(errMsg); flagName != "" {
			if closest := closestFlag(c, flagName); closest != "" {
				//nolint:errcheck // best-effort stderr write
				fmt.Fprintf(errW, "  %s\n", col.Accent("did you mean --"+closest+"?"))
			}
		}
		//nolint:errcheck // best-effort stderr write
		fmt.Fprintf(errW, "  %s\n", col.Dim("→ run `"+c.CommandPath()+" --help` for usage"))

		// Return silentError so Execute() exits with ExitUsage without printing again.
		return silentError{code: output.ExitUsage, err: err}
	})
}

// isArgCountError reports whether the error message looks like a cobra
// argument-count validation failure (generated by cobra.ExactArgs,
// cobra.MinimumNArgs, cobra.MaximumNArgs, cobra.RangeArgs, etc.).
func isArgCountError(msg string) bool {
	return strings.Contains(msg, "arg(s)") ||
		strings.Contains(msg, "accepts between") ||
		strings.Contains(msg, "requires at least") ||
		strings.Contains(msg, "accepts at most") ||
		(strings.Contains(msg, "argument") && strings.Contains(msg, "received"))
}

// printArgCountError writes a colorized error line, the command's full usage
// block, and the first example to w (stderr in the Execute call-site).
func printArgCountError(w io.Writer, cmd *cobra.Command, err error) {
	if cmd == nil {
		//nolint:errcheck // best-effort stderr write
		fmt.Fprintln(w, "✗ "+err.Error())
		return
	}
	styled := interactive.ShouldStyle(cmd, w)
	col := colorizer.New(styled, w)

	//nolint:errcheck // best-effort stderr write
	fmt.Fprintf(w, "%s\n\n", col.Err("✗ "+err.Error()))
	// Write usage to the same stream (stderr). cmd.UsageString() captures
	// the usage text without touching any output writer permanently.
	//nolint:errcheck // best-effort stderr write
	fmt.Fprintln(w, cmd.UsageString())
	if ex := firstExample(cmd.Example); ex != "" {
		//nolint:errcheck // best-effort stderr write
		fmt.Fprintf(w, "Example:\n  %s\n", col.Dim(ex))
	}
}

// firstExample returns the first non-empty, non-comment line from cobra's
// Example field (which is a freeform multi-line string of sample invocations).
func firstExample(example string) string {
	for _, line := range strings.Split(example, "\n") {
		line = strings.TrimSpace(line)
		if line != "" && !strings.HasPrefix(line, "#") {
			return line
		}
	}
	return ""
}

// extractUnknownFlagName parses pflag error messages of the form
//
//	"unknown flag: --NAME"
//	"unknown shorthand flag: 'X' in -X"
//
// and returns the bare flag name (without leading --). Returns "" when the
// message does not match a known pattern.
func extractUnknownFlagName(msg string) string {
	if after, ok := strings.CutPrefix(msg, "unknown flag: --"); ok {
		return strings.TrimSpace(after)
	}
	if strings.HasPrefix(msg, "unknown shorthand flag: '") && len(msg) > len("unknown shorthand flag: '") {
		return string(msg[len("unknown shorthand flag: '")])
	}
	return ""
}

// closestFlag returns the name of the flag in cmd whose edit distance from
// name is smallest, provided that distance is < 4 (otherwise "" is returned
// to avoid noisy suggestions). It visits both local and already-merged
// persistent flags via cmd.Flags().
func closestFlag(cmd *cobra.Command, name string) string {
	best, bestDist := "", 4 // threshold: don't suggest if distance ≥ 4
	cmd.Flags().VisitAll(func(f *pflag.Flag) {
		if d := editDistance(name, f.Name); d > 0 && d < bestDist {
			best, bestDist = f.Name, d
		}
	})
	return best
}

// editDistance computes the Levenshtein edit distance between a and b using
// a single-row dynamic-programming approach (O(min(m,n)) space).
func editDistance(a, b string) int {
	if a == b {
		return 0
	}
	// Compare runes, not bytes, so multi-byte flag names yield correct
	// distances (all cobra flags are ASCII today; this is future-proofing).
	ra, rb := []rune(a), []rune(b)
	m, n := len(ra), len(rb)
	if m == 0 {
		return n
	}
	if n == 0 {
		return m
	}
	dp := make([]int, n+1)
	for j := range dp {
		dp[j] = j
	}
	for i := 1; i <= m; i++ {
		prev := dp[0]
		dp[0] = i
		for j := 1; j <= n; j++ {
			tmp := dp[j]
			if ra[i-1] == rb[j-1] {
				dp[j] = prev
			} else {
				dp[j] = 1 + min(prev, min(dp[j], dp[j-1]))
			}
			prev = tmp
		}
	}
	return dp[n]
}

// silentError is returned by subcommands that have already printed a
// user-facing message and want to exit with a non-zero code without
// Cobra/Execute printing a second copy of the error string.
type silentError struct {
	code int
	err  error
}

func (s silentError) Error() string { return s.err.Error() }
func (s silentError) Unwrap() error { return s.err }

