// newHelpCmd returns a replacement for cobra's built-in help command.
// It exits 1 with a pointer to `maz help-topics` when the topic is unknown.
func newHelpCmd(root *cobra.Command) *cobra.Command {
	hc := &cobra.Command{
		Use:   "help [command]",
		Short: "Help about any command.",
		Long: `Help provides help for any command in the application.
Type maz help [command] for full details.`,
		SilenceUsage:  true,
		SilenceErrors: true,
		RunE: func(c *cobra.Command, args []string) error {
			cmd, _, err := root.Find(args)
			// root.Find returns (root, args, nil) for an unrecognised topic — cmd
			// is never nil and err is nil — so detect "no match" by the resolved
			// command still being root while args remain unconsumed.
			if cmd == nil || err != nil || (cmd == root && len(args) > 0) {
				// Mirror cobra's wording but add a useful hint and exit non-zero.
				topic := strings.Join(args, " ")
				fmt.Fprintf(c.OutOrStderr(), "Unknown help topic %q\nRun \"maz help-topics\" to list available topics.\n", topic) //nolint:errcheck // best-effort stderr write
				return silentError{code: 1, err: fmt.Errorf("unknown help topic %q", topic)}
			}
			// When the resolved target is root, propagate --all onto it so the
			// grouped-help renderer surfaces advanced-tier commands. Subcommands
			// carry no --all flag (and no groups), so the Lookup guard makes this
			// a deliberate no-op for `maz help <subcommand> --all`.
			if all, _ := c.Flags().GetBool("all"); all {
				if cmd.Flags().Lookup("all") != nil {
					cmd.Flags().Set("all", "true") //nolint:errcheck // flag exists (just looked up); value is constant
				}
			}
			cmd.InitDefaultHelpFlag()
			cmd.InitDefaultVersionFlag()
			return cmd.Help()
		},
	}
	// Accept --all on `maz help` itself (parsed against the help command's own
	// flag set); the value is forwarded to the target command in RunE above.
	hc.Flags().BoolP("all", "a", false, "list every command, including advanced ones")
	return hc
}

func persistentPreRun(cmd *cobra.Command, _ []string) error {
	// Validate --output / MAZ_OUTPUT before any work runs. A typo like
	// `--output jsn` used to silently fall back to text-on-TTY /
	// json-off-TTY, which surprised scripts that expected ndjson. Fail
	// fast so the operator sees the typo immediately.
	if explicit, _ := cmd.Flags().GetString("output"); explicit != "" {
		if _, err := output.ParseFormat(explicit); err != nil {
			return fmt.Errorf("--output: %w", err)
		}
	}
	if env := os.Getenv("MAZ_OUTPUT"); env != "" {
		if _, err := output.ParseFormat(env); err != nil {
			return fmt.Errorf("MAZ_OUTPUT=%q: %w", env, err)
		}
	}

	levelStr, _ := cmd.Flags().GetString("log-level")
	flagChanged := cmd.Flags().Changed("log-level")
	level := effectiveLogLevel(flagChanged, levelStr, cmd.CommandPath())
	logger, err := logging.NewLogger(logging.Config{
		Level:  level,
		Format: logging.FormatJSON,
	})
	if err != nil {
		return fmt.Errorf("init logger: %w", err)
	}
	cmd.SetContext(logging.WithLogger(cmd.Context(), logger))

	if addr, _ := cmd.Flags().GetString("debug-addr"); addr != "" {
		startDebugServer(addr, logger)
	}

	// Inject the [output].default_format from the resolved config so that
	// resolveFormat's precedence chain (flag > env > config > TTY) can consult
	// it. The config load is best-effort: a missing or unreadable config.toml is
	// not a fatal error here — the command will simply fall back to the TTY
	// heuristic, consistent with how every command behaves on first-run.
	dataDir, _ := cmd.Flags().GetString("data-dir")
	if dataDir == "" {
		dataDir = config.Defaults().DataDir
	}
	if cfg, cfgErr := config.LoadResolvedConfig(dataDir); cfgErr == nil {
		if cfg.Output.DefaultFormat != "" {
			if f, fErr := output.ParseFormat(cfg.Output.DefaultFormat); fErr == nil {
				output.SetDefaultFormat(f)
			}
		}
	}

	return nil
}

// persistentPostRun runs after a successful one-shot command. It surfaces the
// passive update-check hint; all gating (TTY, format, dev build, CI, disable
// flag, long-running commands) lives in maybeNotifyUpdate, which never blocks
// or errors.
func persistentPostRun(cmd *cobra.Command, _ []string) error {
	maybeNotifyUpdate(cmd)
	return nil
}

// isLongRunningCmd reports whether cmdPath names a command that runs
// indefinitely (mcp serve, watch, internal-daemon-serve). These commands
// warrant INFO-level logging by default so operator-facing wiring logs remain
// visible. One-shot commands default to WARN so piped invocations have a
// clean stderr.
//
// The cmdPath argument is the cobra CommandPath() value, e.g. "maz mcp serve".
func isLongRunningCmd(cmdPath string) bool {
	switch cmdPath {
	case "maz mcp serve", "maz watch", "maz internal-daemon-serve":
		return true
	default:
		return false
	}
}

// resolveLogLevel returns the effective logging.Level from the flag or the
// MAZ_LOG_LEVEL environment variable. The explicit flag wins; the env var
// wins over the compiled-in default when the flag was not set by the user.
func resolveLogLevel(flagChanged bool, flagVal string) logging.Level {
	if flagChanged {
		return parseLevel(flagVal)
	}
	if env := os.Getenv("MAZ_LOG_LEVEL"); env != "" {
		return parseLevel(env)
	}
	return parseLevel(flagVal)
}

// effectiveLogLevel extends resolveLogLevel with the long-running-command
// override: when neither the flag nor MAZ_LOG_LEVEL is set, long-running
// service commands (mcp serve, watch, internal-daemon-serve) use INFO so
// their operator-facing wiring logs remain visible.
func effectiveLogLevel(flagChanged bool, flagVal string, cmdPath string) logging.Level {
	// Explicit flag or env var always wins.
	if flagChanged || os.Getenv("MAZ_LOG_LEVEL") != "" {
		return resolveLogLevel(flagChanged, flagVal)
	}
	// Neither flag nor env: use INFO for long-running servers, WARN for
	// one-shot commands so `maz recall --output json` has clean stderr.
	if isLongRunningCmd(cmdPath) {
		return logging.LevelInfo
	}
	return logging.LevelWarn
}

func parseLevel(s string) logging.Level {
	// Normalise before matching: MAZ_LOG_LEVEL is read verbatim, so common
	// spellings like "DEBUG" or " Error" must map to the intended level
	// rather than silently falling through to the warn default.
	switch strings.ToLower(strings.TrimSpace(s)) {
	case "debug":
		return logging.LevelDebug
	case "warn":
		return logging.LevelWarn
	case "error":
		return logging.LevelError
	case "info":
		return logging.LevelInfo
	default:
		return logging.LevelWarn
	}
}

// runRoot is the handler for bare `maz` (no subcommand). Without the hub,
// it simply prints help.
func runRoot(cmd *cobra.Command, _ []string) error {
	return cmd.Help()
}

func startDebugServer(addr string, logger *zap.Logger) {
	srv := &http.Server{
		Addr:              addr,
		ReadHeaderTimeout: 10 * time.Second,
	}
	go func() {
		logger.Info("debug server listening", zap.String("addr", addr))
		if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
			logger.Warn("debug server error", zap.Error(err))
		}
	}()
}
